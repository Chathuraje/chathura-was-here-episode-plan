import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Which candidate ideas carry which concepts, and what a rejection would cost.
 *
 * A group makes a fixed number of films from more candidates than it can use, so confirming is
 * a subtractive process: every rejection removes that idea's concepts from the slate unless a
 * sibling also carries them. This reports, per group, the concepts carried by only one candidate
 * — where a single rejection would leave the concept with no film at all — and the concepts
 * whose remaining carriers would not fit inside the group's film count.
 *
 * Run: node development/analysis/concept-coverage.mjs
 * Writes development/analysis/concept-coverage.json and docs/planning/09-concept-coverage.md
 */

const analysisDir = path.dirname(fileURLToPath(import.meta.url));
const developmentDir = path.dirname(analysisDir);
const repoDir = path.dirname(developmentDir);

function read(dir) {
  return fs.readdirSync(path.join(developmentDir, dir))
    .filter((name) => name.endsWith(".json"))
    .sort()
    .map((name) => JSON.parse(fs.readFileSync(path.join(developmentDir, dir, name), "utf8")));
}

const ideas = read("ideas");
const groups = read("groups").sort((a, b) => a.chronological_position - b.chronological_position);

const report = groups.map((group) => {
  const own = ideas.filter((idea) => idea.group_id === group.id);
  const needed = group.concepts.map((concept) => concept.id);
  const carriersOf = (conceptId, pool) => pool
    .filter((idea) => idea.concept_links.some((link) => link.concept_id === conceptId))
    .map((idea) => idea.id);

  const confirmed = own.filter((idea) => idea.review?.status === "confirmed");
  const rejected = own.filter((idea) => idea.review?.status === "rejected");
  const live = own.filter((idea) => idea.review?.status !== "rejected");

  const concepts = needed.map((conceptId) => ({
    concept_id: conceptId,
    role_gloss: group.concepts.find((concept) => concept.id === conceptId)?.role ?? "",
    candidates: carriersOf(conceptId, own),
    still_available: carriersOf(conceptId, live),
    confirmed_carriers: carriersOf(conceptId, confirmed),
  }));

  return {
    group_id: group.id,
    title: group.title,
    film_count: group.draft_film_count,
    candidates: own.length,
    confirmed: confirmed.length,
    rejected: rejected.length,
    // One carrier left: rejecting it drops the concept from the series entirely.
    sole_carrier: concepts.filter((entry) => entry.still_available.length === 1),
    // Already unreachable: nothing live carries it.
    lost: concepts.filter((entry) => entry.still_available.length === 0),
    // Confirmed set does not yet carry it.
    not_yet_confirmed: concepts.filter((entry) => entry.confirmed_carriers.length === 0),
    concepts,
  };
});

const summary = {
  generated_at: new Date().toISOString(),
  ideas: ideas.length,
  groups: groups.length,
  concepts_with_one_live_carrier: report.reduce((n, g) => n + g.sole_carrier.length, 0),
  concepts_already_lost: report.reduce((n, g) => n + g.lost.length, 0),
};

fs.writeFileSync(path.join(analysisDir, "concept-coverage.json"),
  `${JSON.stringify({ summary, groups: report }, null, 2)}\n`);

const lines = [
  "# Concept coverage across the candidate slate",
  "",
  "Generated by `development/analysis/concept-coverage.mjs`. Re-run it after any confirmation or rejection.",
  "",
  "Each group makes a fixed number of films from more candidates than it can use, so confirming is",
  "subtractive: a rejection removes that idea's concepts unless a sibling carries them too. The column",
  "that matters is **sole carrier** — a concept held by exactly one idea still in play. Rejecting that",
  "idea removes the concept from the series, and no later group picks it up, because each concept is",
  "placed in exactly one group.",
  "",
  `As of this run: ${summary.ideas} candidates, ${summary.concepts_with_one_live_carrier} concepts held by a single live carrier, ${summary.concepts_already_lost} already with no carrier.`,
  "",
  "| Group | Films | Candidates | Confirmed | Concepts | Held by one idea only |",
  "| --- | --- | --- | --- | --- | --- |",
];
for (const g of report) {
  lines.push(`| ${g.group_id} ${g.title} | ${g.film_count} | ${g.candidates} | ${g.confirmed} | ${g.concepts.length} | ${g.sole_carrier.length ? g.sole_carrier.map((c) => `${c.concept_id} (${c.still_available[0]})`).join(", ") : "—"} |`);
}
for (const g of report) {
  lines.push("", `## ${g.group_id} ${g.title}`, "",
    `${g.film_count} films from ${g.candidates} candidates; ${g.confirmed} confirmed, ${g.rejected} rejected.`, "");
  if (g.lost.length) {
    lines.push(`**Already unreachable:** ${g.lost.map((c) => c.concept_id).join(", ")} — every candidate carrying these has been rejected.`, "");
  }
  lines.push("| Concept | Carried by | Still available | Confirmed |", "| --- | --- | --- | --- |");
  for (const c of g.concepts) {
    const mark = c.still_available.length === 1 ? " ⚠" : c.still_available.length === 0 ? " ✕" : "";
    lines.push(`| ${c.concept_id}${mark} | ${c.candidates.length} | ${c.still_available.join(", ") || "none"} | ${c.confirmed_carriers.join(", ") || "—"} |`);
  }
}
lines.push("", "⚠ one live carrier — rejecting it drops the concept. ✕ no live carrier.", "");
fs.writeFileSync(path.join(repoDir, "docs", "planning", "09-concept-coverage.md"), lines.join("\n"));

console.log(`Wrote coverage for ${summary.ideas} ideas across ${summary.groups} groups.`);
console.log(`Concepts held by a single live carrier: ${summary.concepts_with_one_live_carrier}; already lost: ${summary.concepts_already_lost}`);
